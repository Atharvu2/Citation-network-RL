def load_dataset(paper_path, citation_path):
    # Try multiple encodings
    for enc in ['utf-8', 'latin1', 'iso-8859-1']:
        try:
            papers = pd.read_csv(paper_path, encoding=enc)
            citations = pd.read_csv(citation_path, encoding=enc)
            break
        except:
            continue

    # Clean columns
    papers.columns = papers.columns.str.strip().str.lower()
    citations.columns = citations.columns.str.strip().str.lower()

    # Map to standard names
    col_map = {
        'id': 'paper_id', 'pid': 'paper_id',
        'publication year': 'year', 'pub_year': 'year',
        'source': 'venue', 'journal': 'venue',
        'sid': 'citing', 'tid': 'cited'
    }

    papers.rename(columns={k: v for k, v in col_map.items() if k in papers.columns}, inplace=True)
    citations.rename(columns={k: v for k, v in col_map.items() if k in citations.columns}, inplace=True)

    # Select required columns
    papers = papers[['paper_id', 'year', 'venue']].dropna()
    citations = citations[['citing', 'cited']].dropna()

    # Clean years
    papers['year'] = pd.to_numeric(papers['year'], errors='coerce')
    papers = papers.dropna(subset=['year'])
    papers['year'] = papers['year'].astype(int)
    papers = papers[(papers['year'] >= 1900) & (papers['year'] <= 2024)]

    print(f"✓ Loaded {len(papers):,} papers, {len(citations):,} citations")
    print(f"  Years: {papers['year'].min()}-{papers['year'].max()}")
    print(f"  Venues: {papers['venue'].nunique()}")
    print(f"  Avg citations per paper: {len(citations)/len(papers):.2f}")

    return papers, citations

