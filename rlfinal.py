# ==========================================
# TIME DECAY FUNCTIONS
# ==========================================

def exponential_decay(delta_t, tau=0.117):
    """Exponential decay: W = e^(-τ*Δt)"""
    return np.exp(-tau * delta_t)

def log_decay(delta_t):
    """Log decay: W = 1/(1+ln(1+Δt))"""
    return 1.0 / (1.0 + np.log1p(delta_t))

# ==========================================
# MR-RANK ALGORITHM
# ==========================================

class MRRank:
    """
    MR-Rank: Mutual Reinforcement Ranking Algorithm

    Parameters:
    - alpha (α): Balance between venue prestige and citations (default: 0.4)
    - beta (β): Balance between paper quality and venue citations (default: 0.9)
    - tau (τ): Exponential decay rate (default: 0.117)
    """

    def __init__(self, papers, citations, decay='exponential',
                 tau=0.117, alpha=0.4, beta=0.9,
                 max_iter=100, epsilon=0.001, name='MR-Rank'):
        self.papers = papers.copy()
        self.citations = citations.copy()
        self.decay = decay
        self.tau = tau
        self.alpha = alpha
        self.beta = beta
        self.max_iter = max_iter
        self.epsilon = epsilon
        self.name = name

        self.paper_scores = {}
        self.venue_scores = {}
        self.convergence = []

        self.year_map = dict(zip(papers.paper_id, papers.year))
        self.venue_map = dict(zip(papers.paper_id, papers.venue))
        self._prepare()

    def _prepare(self):
        """Build citation graphs"""
        self.paper_in = defaultdict(list)

        for _, row in self.citations.iterrows():
            citing, cited = row['citing'], row['cited']
            if citing in self.year_map and cited in self.year_map:
                dt = max(0, self.year_map[citing] - self.year_map[cited])
                w = exponential_decay(dt, self.tau) if self.decay == 'exponential' else log_decay(dt)
                self.paper_in[cited].append((citing, w))

        self.venue_cites = defaultdict(lambda: defaultdict(int))
        self.venue_refs = defaultdict(set)

        for _, row in self.citations.iterrows():
            citing, cited = row['citing'], row['cited']
            if citing in self.venue_map and cited in self.venue_map:
                v_citing = f"{self.venue_map[citing]}_{self.year_map[citing]}"
                v_cited = f"{self.venue_map[cited]}_{self.year_map[cited]}"
                self.venue_cites[v_cited][v_citing] += 1
                self.venue_refs[v_citing].add(cited)

    def _get_avg_venue(self, venue, year, lookback=3):
        """Get average venue score from recent years"""
        scores = [self.venue_scores.get(f"{venue}_{y}", 0)
                 for y in range(max(1, year-lookback), year)]
        if not scores:
            scores = [self.venue_scores.get(f"{venue}_{year}", 0)]
        return np.mean(scores) if scores else 0.0

    def run(self):
        """Run iterative MR-Rank algorithm"""
        # Initialize
        n_p = len(self.papers)
        for pid in self.papers.paper_id:
            self.paper_scores[pid] = 1.0 / n_p

        venue_years = set(f"{r['venue']}_{r['year']}" for _, r in self.papers.iterrows())
        n_v = len(venue_years)
        for vy in venue_years:
            self.venue_scores[vy] = 1.0 / n_v

        # Iterate
        for it in range(self.max_iter):
            new_ps, new_vs = {}, {}

            # Update papers (Equation 4)
            for _, p in self.papers.iterrows():
                pid, venue, year = p['paper_id'], p['venue'], p['year']
                avg_venue = self._get_avg_venue(venue, year)
                citation = sum(self.paper_scores.get(c, 0) * w
                              for c, w in self.paper_in.get(pid, []))
                new_ps[pid] = self.alpha * avg_venue + (1 - self.alpha) * citation

            # Update venues (Equation 6)
            for vy in venue_years:
                venue, yr_str = vy.rsplit('_', 1)
                yr = int(yr_str)
                vp = self.papers[(self.papers['venue'] == venue) &
                                (self.papers['year'] == yr)]
                avg_paper = np.mean([new_ps.get(pid, 0) for pid in vp.paper_id]) if len(vp) > 0 else 0

                venue_cit = 0.0
                if vy in self.venue_cites:
                    for cvy, cnt in self.venue_cites[vy].items():
                        total_refs = len(self.venue_refs.get(cvy, set()))
                        if total_refs > 0:
                            venue_cit += self.venue_scores.get(cvy, 0) * (cnt / total_refs)

                new_vs[vy] = self.beta * avg_paper + (1 - self.beta) * venue_cit

            # Normalize
            ps_sum = sum(new_ps.values())
            vs_sum = sum(new_vs.values())
            if ps_sum > 0:
                for k in new_ps: new_ps[k] /= ps_sum
            if vs_sum > 0:
                for k in new_vs: new_vs[k] /= vs_sum

            # Check convergence
            delta = sum(abs(new_ps.get(k, 0) - self.paper_scores.get(k, 0)) for k in new_ps)
            delta += sum(abs(new_vs.get(k, 0) - self.venue_scores.get(k, 0)) for k in new_vs)
            self.convergence.append({'iteration': it+1, 'delta': delta})
            self.paper_scores, self.venue_scores = new_ps, new_vs

            if delta < self.epsilon:
                print(f"  ✓ {self.name}: Converged at iteration {it+1}")
                break

        if delta >= self.epsilon:
            print(f"  ⚠ {self.name}: Max iterations reached")

    def top_papers(self, n=10):
        """Get top N papers by prestige score"""
        sorted_papers = sorted(self.paper_scores.items(), key=lambda x: x[1], reverse=True)[:n]
        results = []
        for pid, score in sorted_papers:
            pinfo = self.papers[self.papers.paper_id == pid].iloc[0]
            results.append({
                'rank': len(results)+1,
                'paper_id': pid,
                'score': score,
                'year': pinfo['year'],
                'venue': pinfo['venue']
            })
        return pd.DataFrame(results)

    def top_venues(self, n=10):
        """Get top N venues by average prestige score"""
        venue_agg = defaultdict(list)
        for vy, score in self.venue_scores.items():
            venue = vy.rsplit('_', 1)[0]
            venue_agg[venue].append(score)

        results = []
        for venue, scores in venue_agg.items():
            results.append({
                'venue': venue,
                'avg_score': np.mean(scores),
                'max_score': np.max(scores),
                'min_score': np.min(scores),
                'n_years': len(scores)
            })

        df = pd.DataFrame(results).sort_values('avg_score', ascending=False).head(n)
        df.insert(0, 'rank', range(1, len(df)+1))
        return df

