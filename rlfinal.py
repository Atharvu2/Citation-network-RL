def load_snap_mtx_dataset(edges_path, nodename_path=None, default_venue="arXiv"):
    """Load SNAP citation network from Matrix Market (.mtx) format"""

    print("\n[1/3] Loading citation edges from MTX file...")

    # Read the MTX file (sparse matrix format)
    # MTX format: row col value (1-indexed)
    citations_list = []

    with open(edges_path, 'r') as f:
        for line in f:
            line = line.strip()
            # Skip comments and empty lines
            if line and not line.startswith('%'):
                parts = line.split()
                if len(parts) >= 2:
                    # MTX is 1-indexed, convert to 0-indexed
                    try:
                        citing = parts[0]
                        cited = parts[1]
                        citations_list.append({'citing': citing, 'cited': cited})
                    except:
                        continue

    citations = pd.DataFrame(citations_list)

    # Remove header row if it exists (dimensions)
    citations = citations[citations['citing'] != citations['cited']]

    print(f"  ✓ Loaded {len(citations):,} citation edges")

    print("\n[2/3] Creating paper metadata...")

    # Get all unique paper IDs
    all_papers = set(citations['citing'].unique()) | set(citations['cited'].unique())
    print(f"  ✓ Found {len(all_papers):,} unique papers")

    # Load node names if available (maps node IDs to actual paper IDs/years)
    node_info = {}
    if nodename_path and os.path.exists(nodename_path):
        print("\n  Loading node name mappings...")
        with open(nodename_path, 'r') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('%'):
                    parts = line.split()
                    if len(parts) >= 2:
                        node_id = parts[0]
                        # Try to extract year from node name if possible
                        node_name = parts[1] if len(parts) > 1 else node_id
                        node_info[node_id] = node_name

    # Since MTX files don't have year info, we'll estimate years
    # based on citation patterns (papers cited more recently tend to be newer)
    print("\n[3/3] Estimating publication years from citation patterns...")

    # Count citations for each paper
    citation_counts = citations['cited'].value_counts().to_dict()

    # Build citation graph to estimate years
    cites_dict = defaultdict(set)
    for _, row in citations.iterrows():
        cites_dict[row['citing']].add(row['cited'])

    # Estimate years using topological ordering
    # Papers with no incoming citations are oldest
    # Papers that cite many others are newer
    paper_levels = {}

    def get_level(paper_id, visited=None):
        if visited is None:
            visited = set()
        if paper_id in visited:
            return 0
        if paper_id in paper_levels:
            return paper_levels[paper_id]

        visited.add(paper_id)
        cited_papers = cites_dict.get(paper_id, set())

        if not cited_papers:
            level = 0
        else:
            max_cited_level = max([get_level(p, visited.copy()) for p in cited_papers], default=0)
            level = max_cited_level + 1

        paper_levels[paper_id] = level
        return level

    # Calculate levels for all papers
    for pid in all_papers:
        if pid not in paper_levels:
            get_level(pid)

    # Convert levels to years (spread across reasonable range)
    min_level = min(paper_levels.values())
    max_level = max(paper_levels.values())

    # Map to years 1990-2005 (typical for HEP papers)
    start_year = 1990
    end_year = 2005
    year_range = end_year - start_year

    papers_list = []
    for paper_id in all_papers:
        level = paper_levels.get(paper_id, 0)
        if max_level > min_level:
            normalized_level = (level - min_level) / (max_level - min_level)
            year = int(start_year + normalized_level * year_range)
        else:
            year = start_year

        papers_list.append({
            'paper_id': paper_id,
            'year': year,
            'venue': default_venue
        })

    papers = pd.DataFrame(papers_list)

    # Filter citations to valid papers only
    valid_papers = set(papers['paper_id'])
    citations = citations[
        citations['citing'].isin(valid_papers) &
        citations['cited'].isin(valid_papers)
    ]
    citations = citations[citations['citing'] != citations['cited']]

    print(f"\n✓ Dataset Ready:")
